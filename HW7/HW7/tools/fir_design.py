"""Design the FIR low-pass filter and emit App/Inc/fir_coeffs.h.

Windowed-sinc (Hamming) design, normalised to unity DC gain.
This is the same algorithm as scipy.signal.firwin(NUM_TAPS, FC, fs=FS),
written with the standard library only so it runs without extra packages.

Usage:  python tools/fir_design.py
"""
import math
from pathlib import Path

FS = 100.0      # sampling rate [Hz]  (TIM7 = 100 Hz)
FC = 5.0        # cut-off frequency [Hz]
NUM_TAPS = 31   # odd -> linear phase type I, group delay = 15 samples

OUT = Path(__file__).resolve().parent.parent / "App" / "Inc" / "fir_coeffs.h"


def design(num_taps: int, fc: float, fs: float) -> list[float]:
    wc = 2.0 * fc / fs                      # normalised cut-off (Nyquist = 1)
    m = (num_taps - 1) / 2.0
    h = []
    for n in range(num_taps):
        x = n - m
        sinc = 1.0 if x == 0 else math.sin(math.pi * wc * x) / (math.pi * wc * x)
        win = 0.54 - 0.46 * math.cos(2.0 * math.pi * n / (num_taps - 1))
        h.append(wc * sinc * win)
    s = sum(h)
    return [v / s for v in h]


def gain_db(h: list[float], f: float, fs: float) -> float:
    w = 2.0 * math.pi * f / fs
    re = sum(c * math.cos(w * n) for n, c in enumerate(h))
    im = -sum(c * math.sin(w * n) for n, c in enumerate(h))
    return 20.0 * math.log10(max(math.hypot(re, im), 1e-12))


def main() -> None:
    h = design(NUM_TAPS, FC, FS)
    body = ",\n".join(f"    {c: .10e}f" for c in h)
    OUT.write_text(
        "/* Auto-generated by tools/fir_design.py - do not edit by hand. */\n"
        "#ifndef FIR_COEFFS_H\n#define FIR_COEFFS_H\n\n"
        f"/* Hamming windowed-sinc low-pass, fs = {FS:g} Hz, fc = {FC:g} Hz */\n"
        f"#define FIR_FS_HZ      {FS:.1f}f\n"
        f"#define FIR_FC_HZ      {FC:.1f}f\n"
        f"#define FIR_NUM_TAPS   {NUM_TAPS}\n\n"
        "static const float fir_coeffs[FIR_NUM_TAPS] = {\n"
        f"{body}\n}};\n\n#endif /* FIR_COEFFS_H */\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT}")
    for f in (0, 2, 5, 10, 20, 30, 50):
        print(f"  |H({f:>2} Hz)| = {gain_db(h, f, FS):8.2f} dB")


if __name__ == "__main__":
    main()
